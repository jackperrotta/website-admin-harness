import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, mkdir, readFile, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {schedulingConnect} from '../packages/admin/bin/scheduling-connect.ts';

test('scheduling connection plans preserve website fields, require reviewed exact inputs and safely retry locally without a backend', async () => {
  const root = await mkdtemp(join(tmpdir(),'vitris-scheduling-connect-')), site = join(root,'website'), admin = join(root,'admin');
  await mkdir(site); await mkdir(admin);
  const manifest = {schemaVersion:1,installationId:'test-install',business:{name:'Synthetic',initials:'S'},site:{id:'test-site',name:'Website',origin:'http://localhost:4392'},adminOrigin:'http://localhost:4391',modules:['scheduling']};
  const launch = {slug:'synthetic',publicOrigin:manifest.site.origin,forms:[{id:'preserved'}],backendOrigin:'https://preserved.example.test',other:{keep:true}};
  const manifestPath = join(admin,'admin.local.json'), launchPath = join(site,'launch.json');
  await writeFile(manifestPath,JSON.stringify(manifest)); await writeFile(launchPath,JSON.stringify(launch));
  const options = {site,dir:admin,local:true}, packageRoot = resolve('packages/admin');
  await assert.rejects(schedulingConnect({...options,dir:join(site,'..admin'),plan:true},packageRoot),/separate/);
  await assert.rejects(schedulingConnect({...options,apply:true},packageRoot));
  await schedulingConnect({...options,plan:true},packageRoot);
  assert.deepEqual(JSON.parse(await readFile(launchPath,'utf8')),launch);
  await writeFile(manifestPath,JSON.stringify({...manifest,installationId:'changed'}));
  await assert.rejects(schedulingConnect({...options,apply:true},packageRoot),/changed/);
  await writeFile(manifestPath,JSON.stringify(manifest));
  await writeFile(launchPath,JSON.stringify({...launch,other:'changed'}));
  await assert.rejects(schedulingConnect({...options,apply:true},packageRoot),/changed/);
  await writeFile(launchPath,JSON.stringify(launch));
  await schedulingConnect({...options,apply:true},packageRoot); await schedulingConnect({...options,apply:true},packageRoot);
  const connected = JSON.parse(await readFile(launchPath,'utf8'));
  assert.deepEqual(connected,{...launch,scheduling:{version:1,enabled:true,apiOrigin:manifest.adminOrigin,siteId:manifest.site.id,installationId:manifest.installationId,route:'/book'}});
  assert.equal(await readFile(manifestPath,'utf8'),JSON.stringify(manifest));
  await assert.rejects(schedulingConnect({...options,apply:true,route:'/different'},packageRoot),/differs/);
  await assert.rejects(schedulingConnect({...options,plan:true,route:'/api/book'},packageRoot),/safe/);
  await writeFile(launchPath,JSON.stringify({...launch,publicOrigin:'http://localhost:9999'}));
  await assert.rejects(schedulingConnect({...options,plan:true},packageRoot),/origin/);
  await writeFile(launchPath,JSON.stringify(launch));
  await writeFile(join(admin,'admin.config.json'),JSON.stringify(manifest));
  await assert.rejects(schedulingConnect({site,dir:admin,plan:true},packageRoot),/explicit --local/);
  await writeFile(manifestPath,JSON.stringify({...manifest,site:{...manifest.site,origin:'https://customer.example.test'}}));
  await assert.rejects(schedulingConnect({...options,plan:true},packageRoot),/loopback/);
});
