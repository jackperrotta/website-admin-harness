test('editor previews exact unsaved copy and questions, preserves the draft, and saves only on request',{timeout:120000},async()=>{
  const f=await createPortfolioFixture({onboarding:true}),browser=await chromium.launch({headless:true});
  const workspace=async()=>(await (await f.app.dispatchFetch(f.origin+'/api/modules/client-onboarding',{headers:{cookie:f.cookies.owner}})).json()) as ProspectWorkspace;
  try {
    const source=(await workspace()).templates[0];
    const response=await f.app.dispatchFetch(f.origin+'/api/modules/client-onboarding/templates',{method:'POST',headers:{cookie:f.cookies.owner,origin:f.origin,'content-type':'application/json'},body:JSON.stringify({...source,name:'Original welcome',title:'Original headline',message:'Original invitation',fields:[{id:'service',label:'Main service',kind:'text',section:'business',required:true,value:''},{id:'goals',label:'Website goals',kind:'textarea',section:'website',required:false,value:''}]})});
    assert.equal(response.status,200);
    const original=(await workspace()).templates.find(t=>t.name==='Original welcome')!;
    const page=await browser.newPage({viewport:{width:1536,height:1100}}),writes:string[]=[],errors:string[]=[];
    page.on('request',r=>{if(r.method()!=='GET'&&r.url().includes('/api/'))writes.push(new URL(r.url()).pathname);});page.on('pageerror',e=>errors.push(e.message));
    await page.context().addCookies([{name:'vitris-admin-local',value:'synthetic-portfolio-owner',url:f.origin}]);
    await page.goto(f.origin+'/#client-onboarding?view=templates');
    const card=page.locator('.ob-template-card').filter({has:page.getByRole('heading',{name:'Original welcome',exact:true})});
    await card.getByRole('button',{name:'Edit template',exact:true}).click();
    await page.getByLabel('Template name',{exact:true}).fill('A welcome for studios');
    await page.getByLabel('Business type',{exact:true}).fill('Design studios');
    await page.getByLabel(/^Welcome message/).fill('Your studio’s first look, ready to explore.');
    await page.getByLabel('Client signup headline',{exact:true}).fill('Let’s shape your studio.');
    await page.getByLabel(/^Client signup introduction/).fill('A welcome designed around your studio.');
    await page.getByLabel('Field 1 label',{exact:true}).fill('What makes your studio special?');
    await page.getByLabel('Helpful hint',{exact:true}).first().fill('Tell us about your approach.');
    await page.getByLabel('Field 1 format',{exact:true}).selectOption('textarea');
    await page.getByLabel('Required',{exact:true}).first().uncheck();
    await page.getByLabel('Include payment-method setup',{exact:false}).uncheck();
    await page.getByRole('button',{name:'Preview changes',exact:true}).first().click();
    await page.getByText('Unsaved changes.',{exact:true}).waitFor();
    await page.getByText('Your studio’s first look, ready to explore.',{exact:true}).waitFor();
    assert.equal(await page.getByRole('dialog').count(),0);assert.equal(await page.getByRole('navigation',{name:'Main navigation'}).count(),0);
    assert.deepEqual(await page.getByLabel('Preview step',{exact:true}).locator('option').allTextContents(),['Welcome & site preview','Your business','Your website','Your account','Completion']);
    await page.getByLabel('Preview step',{exact:true}).selectOption('business');
    await page.getByRole('heading',{name:'Let’s shape your studio.',exact:true}).waitFor();
    await page.getByText('A welcome designed around your studio.',{exact:true}).waitFor();
    const question=page.getByRole('textbox',{name:/What makes your studio special/});
    assert.equal(await question.evaluate(el=>el.tagName),'TEXTAREA');assert.equal(await question.getAttribute('required'),null);
    await page.getByText('Tell us about your approach.',{exact:true}).waitFor();
    await mkdir('artifacts/template-draft-preview',{recursive:true});await page.screenshot({path:'artifacts/template-draft-preview/desktop.png',fullPage:true});
    await page.getByRole('button',{name:'Phone',exact:true}).click();
    assert.ok(await page.locator('.tp-canvas>.oj-root').evaluate(el=>el.getBoundingClientRect().width<=390));
    await page.setViewportSize({width:390,height:844});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:'artifacts/template-draft-preview/mobile.png',fullPage:true});
    await question.fill('A temporary preview answer');await page.getByRole('button',{name:'Reset preview',exact:true}).click();
    await page.getByLabel('Preview step',{exact:true}).selectOption('business');assert.equal(await question.inputValue(),'');
    await page.getByRole('button',{name:'Use sample answers',exact:true}).click();
    await page.getByRole('button',{name:/Save & continue/}).click();await page.getByRole('heading',{name:'Tell us what matters.'}).waitFor();
    await page.getByRole('button',{name:/Save & continue/}).click();await page.getByRole('heading',{name:'Your space starts here.'}).waitFor();
    await page.getByRole('button',{name:/Preview account creation/}).click();await page.getByRole('heading',{name:'You’re all set, Riley.'}).waitFor();
    assert.deepEqual(writes,[]);assert.deepEqual((await workspace()).templates.find(t=>t.id===original.id),original);
    assert.equal((await workspace()).rows.length,0);
    await page.getByRole('button',{name:'← Back to editing',exact:true}).click();
    assert.equal(await page.getByLabel('Template name',{exact:true}).inputValue(),'A welcome for studios');
    assert.equal(await page.getByLabel('Business type',{exact:true}).inputValue(),'Design studios');
    assert.equal(await page.getByLabel('Field 1 label',{exact:true}).inputValue(),'What makes your studio special?');
    assert.equal(await page.getByLabel('Helpful hint',{exact:true}).first().inputValue(),'Tell us about your approach.');
    assert.equal(await page.getByLabel('Field 1 format',{exact:true}).inputValue(),'textarea');
    assert.equal(await page.getByLabel('Required',{exact:true}).first().isChecked(),false);
    assert.equal(await page.getByLabel('Include payment-method setup',{exact:false}).isChecked(),false);
    await page.getByLabel('Field 2 step',{exact:true}).selectOption('business');
    await page.getByRole('button',{name:'Preview changes',exact:true}).last().click();
    assert.deepEqual(await page.getByLabel('Preview step',{exact:true}).locator('option').allTextContents(),['Welcome & site preview','Your business','Your account','Completion']);
    await page.goBack();await page.getByLabel('Template name',{exact:true}).waitFor();
    assert.equal(await page.getByLabel('Field 2 step',{exact:true}).inputValue(),'business');
    await page.getByRole('button',{name:'Save template →',exact:true}).click();
    await page.getByRole('heading',{name:'A welcome for studios',exact:true}).waitFor();
    const saved=(await workspace()).templates.find(t=>t.id===original.id)!;
    assert.equal(saved.revision,original.revision+1);assert.equal(saved.title,'Let’s shape your studio.');assert.equal(saved.requiresPayment,false);
    assert.ok(saved.fields.every(f=>f.value===''));assert.equal(saved.fields[1].section,'business');
    assert.deepEqual(writes,['/api/modules/client-onboarding/templates/'+original.id]);assert.deepEqual(errors,[]);
  }finally{await browser.close();await f.app.dispose();}
});

test('new incomplete templates preview before saving, return intact, and never persist across reload or module exit',{timeout:120000},async()=>{
  const f=await createPortfolioFixture({onboarding:true}),browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage(),writes:string[]=[];
    page.on('request',r=>{if(r.method()!=='GET'&&r.url().includes('/api/'))writes.push(r.url());});
    await page.context().addCookies([{name:'vitris-admin-local',value:'synthetic-portfolio-owner',url:f.origin}]);
    await page.goto(f.origin+'/#client-onboarding?view=templates');
    await page.getByRole('button',{name:'＋ Create template',exact:true}).click();
    await page.getByRole('button',{name:'＋ Add field',exact:true}).click();
    await page.getByRole('button',{name:'Preview changes',exact:true}).first().click();
    await page.getByRole('heading',{name:'Untitled template',exact:true}).waitFor();
    await page.getByRole('button',{name:'← Back to editing',exact:true}).click();
    assert.equal(await page.getByLabel('Template name',{exact:true}).inputValue(),'');assert.equal(await page.getByLabel('Field 4 label',{exact:true}).inputValue(),'');
    await page.getByLabel('Template name',{exact:true}).fill('Not saved');
    await page.getByRole('button',{name:'Preview changes',exact:true}).first().click();
    await page.getByRole('heading',{name:'Not saved',exact:true}).waitFor();
    await page.reload();await page.getByRole('heading',{name:'Draft preview unavailable.',exact:true}).waitFor();
    await page.getByRole('button',{name:'← Back to templates',exact:true}).click();
    await page.getByRole('button',{name:'＋ Create template',exact:true}).click();
    await page.getByLabel('Template name',{exact:true}).fill('Another unsaved draft');
    await page.getByRole('link',{name:'Overview',exact:true}).click();await page.getByRole('heading',{name:'Your website, at a glance.',exact:true}).waitFor();
    await page.goto(f.origin+'/#client-onboarding?preview-draft=1');
    await page.getByRole('heading',{name:'Draft preview unavailable.',exact:true}).waitFor();
    assert.deepEqual(writes,[]);assert.equal((await f.db.prepare('SELECT COUNT(*) n FROM client_onboarding_templates').first<{n:number}>())?.n,0);
    assert.equal((await f.db.prepare('SELECT COUNT(*) n FROM client_onboarding_prospects').first<{n:number}>())?.n,0);
  }finally{await browser.close();await f.app.dispose();}
});
