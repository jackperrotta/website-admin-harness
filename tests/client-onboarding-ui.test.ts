import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
import {createPortfolioFixture} from './client-portfolio-fixture.ts';

test('owner prepares client-specific onboarding; prospect previews before signup and completes a separate client dashboard', {timeout: 180000}, async () => {
  const fixture = await createPortfolioFixture({onboarding: true}), browser = await chromium.launch({headless: true});
  try {
    const owner = await browser.newPage({viewport: {width: 1536, height: 1100}}), errors: string[] = [];
    owner.on('pageerror', e => errors.push(e.message));
    await owner.context().addCookies([{name: 'vitris-admin-local', value: 'synthetic-portfolio-owner', url: fixture.origin}]);
    await owner.goto(`${fixture.origin}/#client-onboarding`);
    await owner.getByRole('heading', {name: 'From first look to welcome aboard.'}).waitFor();
    await owner.getByRole('button', {name: 'Prepare your first prospect'}).click();
    const form = owner.getByRole('dialog', {name: 'Prepare a prospect account'});
    await form.getByLabel('Business name', {exact: true}).fill('Alder & Stone');
    await form.getByLabel('Contact name', {exact: true}).fill('Morgan Ellis');
    await form.getByLabel('Contact email', {exact: true}).fill('morgan@example.test');
    await form.getByLabel('Field 2 prefilled value', {exact: true}).fill('100 Example Avenue');
    await form.getByRole('button', {name: 'Add field'}).click();
    await form.getByLabel('Field 4 label', {exact: true}).fill('Preferred launch date');
    await form.locator('.ob-field-editor').nth(3).getByRole('checkbox', {name: 'Required'}).check();
    await mkdir('artifacts/client-onboarding', {recursive: true});
    await form.screenshot({path: resolve('artifacts/client-onboarding/prepare-desktop.png')});
    await form.getByRole('button', {name: 'Prepare account'}).click();
    await owner.getByRole('button', {name: 'Manage', exact: false}).click();
    await owner.getByRole('button', {name: 'Generate setup link', exact: true}).click();
    const invitation = owner.getByRole('dialog', {name: 'Their invitation is ready'});
    await invitation.waitFor();
    const url = await invitation.getByLabel('Local setup link').inputValue();
    await invitation.getByRole('button', {name: 'Close dialog', exact: true}).click();
    await owner.getByRole('dialog', {name: 'Alder & Stone', exact: true}).getByRole('button', {name: 'Close dialog'}).click();
    await owner.screenshot({path: resolve('artifacts/client-onboarding/owner-desktop.png'), fullPage: true});
    const context = await browser.newContext({viewport: {width: 1440, height: 1050}}), client = await context.newPage();
    client.on('pageerror', e => errors.push(e.message));
    await client.goto(url);
    await client.getByRole('heading', {name: 'A little preview, Morgan.'}).waitFor();
    assert.equal(new URL(client.url()).hash, '');
    assert.equal(await client.getByRole('link', {name: 'Clients', exact: true}).count(), 0);
    await client.screenshot({path: resolve('artifacts/client-onboarding/prospect-preview-desktop.png'), fullPage: true});
    await client.getByRole('button', {name: 'Complete signup'}).click();
    const signup = client.locator('.oj-form-panel');
    assert.equal(await client.getByRole('dialog').count(), 0);
    assert.equal(await signup.getByLabel(/Business address/).inputValue(), '100 Example Avenue');
    await signup.getByLabel(/Business phone/).fill('555-0100');
    await signup.getByLabel(/Preferred launch date/).fill('Next month');
    await client.setViewportSize({width: 390, height: 844});
    assert.ok(await signup.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    await signup.screenshot({path: resolve('artifacts/client-onboarding/signup-mobile.png')});
    await signup.getByRole('button', {name: /Save & continue/}).click();
    await client.getByRole('heading', {name: 'Tell us what matters.'}).waitFor();
    await signup.getByRole('button', {name: /Save & continue/}).click();
    await client.getByRole('heading', {name: 'Your space starts here.'}).waitFor();
    await client.reload();
    await client.getByRole('heading', {name: 'Your space starts here.'}).waitFor();
    await signup.getByLabel('Choose a password', {exact: false}).fill('a local sample password for testing');
    await signup.getByLabel('Confirm password', {exact: true}).fill('a local sample password for testing');
    await signup.getByRole('button', {name: /Create my client account/}).click();
    await client.getByRole('heading', {name: 'One last thing.'}).waitFor();
    assert.equal(await client.getByRole('dialog').count(), 0);
    assert.equal(await client.locator('input').count(), 0);
    await client.getByRole('button', {name: 'Simulate saved payment method'}).click();
    await client.getByRole('heading', {name: 'You’re all set, Morgan.'}).waitFor();
    await client.screenshot({path: resolve('artifacts/client-onboarding/payment-mobile.png'), fullPage: true});
    await client.getByRole('button', {name: /Open my dashboard/}).click();
    await client.getByRole('button', {name: 'Your test site', exact: true}).click();
    await client.getByLabel('Website feedback').fill('The layout feels clear. Could the contact link stand out more?');
    await client.getByRole('button', {name: /Save feedback/}).click();
    await client.getByText('Feedback saved for your website team.').waitFor();
    assert.ok(await client.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await client.screenshot({path: resolve('artifacts/client-onboarding/client-mobile.png'), fullPage: true});
    await client.reload(); await client.getByRole('heading', {name: 'Welcome aboard, Morgan.'}).waitFor();
    await client.getByRole('button', {name: 'Your details', exact: true}).click();
    await client.getByText('Next month', {exact: true}).waitFor();
    await owner.getByRole('button', {name: 'Refresh', exact: false}).click();
    await owner.getByText('Sample method saved', {exact: true}).waitFor();
    await owner.getByRole('button', {name: 'Manage', exact: false}).click();
    await owner.getByText('The layout feels clear.', {exact: false}).waitFor();
    await owner.getByRole('button', {name: 'Revoke access', exact: true}).click();
    await owner.getByRole('dialog', {name: 'Revoke prospect access?'}).getByRole('button', {name: 'Revoke access', exact: true}).click();
    await client.reload(); await client.getByRole('heading', {name: 'Welcome back.'}).waitFor();
    assert.deepEqual(errors, []);
  } finally {await browser.close(); await fixture.app.dispose();}
});
