import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtemp,readFile,writeFile,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
const npmCLI=process.env.npm_execpath;
const npm=(args,cwd)=>execFileSync(process.execPath,[npmCLI,...args],{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']});
const cli=resolve('packages/admin/bin/admin.mjs');
const command=(args,cwd)=>execFileSync(process.execPath,[cli,...args],{cwd,encoding:'utf8'});
test('packed npm packages scaffold an external installation, agent kit, and safe website connection',async()=>{
  assert.ok(npmCLI,'Run tests using npm test');
  const root=await mkdtemp(join(tmpdir(),'vitris-admin-package-'));
  const runtime=JSON.parse(npm(['pack','--json','--pack-destination',root],resolve('packages/admin')))[0];
  const initializer=JSON.parse(npm(['pack','--json','--pack-destination',root],resolve('packages/create-admin')))[0];
  const paths=runtime.files.map(x=>x.path);
  assert.ok(paths.includes('dist/worker.js')&&paths.includes('dist/client/index.html')&&paths.includes('agent/WORKFLOW.md'));
  assert.ok(paths.every(x=>!/(?:\.dev\.vars|admin\.config|\.wrangler|bootstrap-owner)/.test(x)));
  const tool=join(root,'tool');await mkdir(tool);
  npm(['install','--ignore-scripts','--no-audit','--no-fund',join(root,runtime.filename),join(root,initializer.filename)],tool);
  const target=join(root,'acme-admin');
  execFileSync(process.execPath,[join(tool,'node_modules/@vitris/create-admin/index.mjs'),'--dir',target,'--slug','acme','--name','Acme Business','--domain','admin.acme.test','--website','https://acme.test'],{cwd:tool,encoding:'utf8'});
  const manifest=JSON.parse(await readFile(join(target,'admin.config.json'),'utf8'));assert.equal(manifest.adminOrigin,'https://admin.acme.test');
  const config=JSON.parse(await readFile(join(target,'wrangler.jsonc'),'utf8'));assert.equal(config.vars.MODE,'production');assert.equal(config.workers_dev,false);
  npm(['install','--ignore-scripts','--no-audit','--no-fund',join(root,runtime.filename)],target);
  execFileSync(process.execPath,[resolve('node_modules/wrangler/bin/wrangler.js'),'deploy','--dry-run','--config','wrangler.local.jsonc','--outdir','dist'],{cwd:target,encoding:'utf8',stdio:['ignore','pipe','pipe']});
  assert.match(await readFile(join(target,'agent/WORKFLOW.md'),'utf8'),/Cloudflare/);
  assert.throws(()=>command(['init','--dir',target],root));
  command(['module','--dir',target,'--slug','estimates','--name','Estimates'],root);
  assert.match(await readFile(join(target,'modules/estimates/index.js'),'utf8'),/request.method !== 'GET'/);
  const website=join(root,'website');await mkdir(website);await writeFile(join(website,'launch.json'),JSON.stringify({slug:'acme',backendOrigin:'https://existing.test',forms:[{id:'keep-me'}]}));
  command(['connect','--dir',target,'--site',website,'--plan'],root);
  assert.equal(JSON.parse(await readFile(join(website,'launch.json'),'utf8')).admin,undefined);
  command(['connect','--dir',target,'--site',website,'--apply'],root);
  const launch=JSON.parse(await readFile(join(website,'launch.json'),'utf8'));assert.equal(launch.admin.url,'https://admin.acme.test');assert.equal(launch.backendOrigin,'https://existing.test');assert.equal(launch.forms[0].id,'keep-me');
  command(['connect','--dir',target,'--site',website,'--apply'],root);
});
